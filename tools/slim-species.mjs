// tools/slim-species.mjs — cut Cybernetic Ecology's species data down to the old ones this game uses.
//
// shared/ecology/ecology-species.js in interactions_library holds all 41 species (~20 MB, most of it
// line/fill meshes). The game only needs the handful listed in src/content/old-ones.js, so this script
// loads the full file, keeps those species and every table entry that refers to them, and drops
// references to species that are not kept (prey, hosts, evolution targets) so the sim never looks up
// a missing index.
//
//   node tools/slim-species.mjs [path/to/interactions_library]
//
// Writes public/vendor/forge/ecology-species.slim.js. Re-run it whenever the roster in
// src/content/old-ones.js changes or the species art in interactions_library is updated.

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { OLD_ONES } from "../src/content/old-ones.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const libRoot = process.argv[2] || path.resolve(here, "../../interactions_library");
const src = path.join(libRoot, "shared/ecology/ecology-species.js");
const out = path.resolve(here, "../public/vendor/forge/ecology-species.slim.js");

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(src, "utf8"), ctx);
const E = ctx.window.EcologySpecies;

const keep = OLD_ONES.map((o) => o.key);
const missing = keep.filter((k) => !E.SPECIES.some((s) => s.key === k));
if (missing.length) throw new Error(`not in ecology-species.js: ${missing.join(", ")}`);
const kept = new Set(keep);
const only = (list) => (list || []).filter((k) => kept.has(k));
const pick = (obj) => Object.fromEntries(Object.entries(obj || {}).filter(([k]) => kept.has(k)));

const SPECIES = E.SPECIES.filter((s) => kept.has(s.key));
const BEH = pick(E.BEH);
for (const b of Object.values(BEH)) {
  if (b.prey) b.prey = only(b.prey);
  if (b.hosts) b.hosts = only(b.hosts);
}
const ECO = pick(E.ECO);
for (const e of Object.values(ECO)) {
  e.eats = only(e.eats);
  if (e.hosts) e.hosts = only(e.hosts);
}
const EVOLVE = pick(E.EVOLVE);
for (const e of Object.values(EVOLVE)) e.next = only(e.next);

const data = {
  SPECIES, BEH, ECO, EVOLVE,
  WING: pick(E.WING), HUE: pick(E.HUE), DEFAULT_COL_HI: E.DEFAULT_COL_HI,
  TIER1_KEYS: only(E.TIER1_KEYS), TIER2_KEYS: only(E.TIER2_KEYS), TIER3_KEYS: only(E.TIER3_KEYS),
};

const header = `// GENERATED by tools/slim-species.mjs from interactions_library/shared/ecology/ecology-species.js.
// Do not edit by hand: change src/content/old-ones.js and re-run the tool.
// Species: ${keep.join(", ")}\n`;
fs.writeFileSync(out, header + "window.EcologySpecies = " + JSON.stringify(data) + ";\n");
console.log(`wrote ${path.relative(process.cwd(), out)} (${(fs.statSync(out).size / 1024 / 1024).toFixed(2)} MB, ${SPECIES.length} species)`);
