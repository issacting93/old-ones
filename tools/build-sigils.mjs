// tools/build-sigils.mjs — draw the old ones' sigil words with Sigil Forge.
//
// Runs interactions_library's alphabet generator (shared/generators/sigil-generator.js) on the
// creature-parts kit, in Sigil Forge's own "creature" style, and keeps one glyph per word in
// src/content/sigils.js. The 1.8 MB parts kit is only needed here, never at runtime: the output is
// a small file of finished SVG fragments.
//
//   node tools/build-sigils.mjs [path/to/interactions_library] [seed]
//
// Writes src/content/sigil-glyphs.js. Re-run after adding a word or to try another alphabet seed.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { WORDS } from "../src/content/sigils.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const lib = process.argv[2] || path.resolve(here, "../../interactions_library");
const seed = Number(process.argv[3]) || 2026;

const ctx = { window: {}, console };
vm.createContext(ctx);
for (const f of ["shared/generators/kit-utils.js", "shared/generators/sigil-generator.js"]) vm.runInContext(fs.readFileSync(path.join(lib, f), "utf8"), ctx);
const { ForgeKit, SigilGenerator } = ctx.window;
const raw = JSON.parse(fs.readFileSync(path.join(lib, "shared/creature-parts.json"), "utf8"));
const parts = ForgeKit.tagRoles(Array.isArray(raw) ? raw : raw.parts || Object.values(raw));
const byId = Object.fromEntries(parts.map((p) => [p.id, p]));

// Sigil Forge's own default alphabet (tools/sigil-forge/index.html), seeded
const R = ForgeKit.rng(seed);
const pick = (role) => { const a = parts.filter((p) => p.roles.includes(role) && !p.defs && /stroke="#/.test(p.svg)); return a.length ? a[Math.floor(R() * a.length)].id : null; };
const A = SigilGenerator.newAlphabet(seed, { cols: 3, rows: 4, diag: true, min: 4, max: 8, cross: 1, dist: 3, style: "creature", w: 3.4, orn: 0.7, hook: pick("hook"), bead: pick("bead") });

const INK = "#e9e1cf";
const out = {};
WORDS.forEach((w, i) => {
  const gl = A.glyphs[(i * 5 + 3) % A.glyphs.length];
  const defs = new Map();
  const frag = SigilGenerator.glyphSvg(A, gl, 50, 50, 60, { color: INK, defs }, byId, parts);
  out[w.id] = ([...defs.values()].join("") + frag).replaceAll(INK, "currentColor").replaceAll(INK.toUpperCase(), "currentColor");
});
const file = `// GENERATED by tools/build-sigils.mjs from Sigil Forge (interactions_library), alphabet seed ${seed}.
// One glyph per word in src/content/sigils.js, as SVG fragments in a 100 × 100 box, inked in currentColor.
export const GLYPHS = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.resolve(here, "../src/content/sigil-glyphs.js"), file);
console.log(`wrote src/content/sigil-glyphs.js (${(file.length / 1024).toFixed(1)} KB, ${WORDS.length} glyphs)`);
